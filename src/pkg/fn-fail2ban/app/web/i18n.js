  function normalize(lang) {
    if (!lang) return null;
    lang = String(lang).toLowerCase();
    if (lang.indexOf('zh') === 0) return 'zh';
    if (lang.indexOf('en') === 0) return 'en';
    return SUPPORTED.indexOf(lang) >= 0 ? lang : null;
  }

  function currentLang() {
    try {
      var saved = global.localStorage && global.localStorage.getItem(LANG_KEY);
      return normalize(saved) || DEFAULT_LANG;
    } catch (e) {
      return DEFAULT_LANG;   // 隐私模式下 localStorage 会抛错
    }
  }

  function has(key, lang) {
    var table = DICT[lang || currentLang()] || DICT[DEFAULT_LANG] || {};
    return Object.prototype.hasOwnProperty.call(table, key);
  }

  /* 查表 + {name} 占位替换。查不到返回 key 本身（实机上一眼能看出漏翻），并 warn 一次。 */
  function t(key, params) {
    if (key === null || key === undefined) return '';
    key = String(key);
    var lang = currentLang();
    var table = DICT[lang] || DICT[DEFAULT_LANG];
    var text = table[key];
    if (typeof text !== 'string') {
      if (!warned[key]) {
        warned[key] = true;
        if (global.console && console.warn) {
          console.warn('[i18n] missing key: "' + key + '" (lang=' + lang + ')');
        }
      }
      return key;
    }
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, function (m, name) {
      var v = params[name];
      return v === null || v === undefined ? m : String(v);
    });
  }

